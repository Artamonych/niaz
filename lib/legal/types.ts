/**
 * Правовые документы сайта: политика по персональным данным и политика cookie.
 *
 * Текст лежит структурой, а не разметкой, чтобы обе страницы рисовал один
 * компонент, а сам документ можно было вычитывать и править как текст.
 * Юридические формулировки согласуются с заказчиком — код их не сочиняет.
 */
export type LegalBlock =
  | { p: string }
  | { list: string[] }
  | { ol: string[] }
  | { table: { head: string[]; rows: string[][] } };

export type LegalSection = {
  /** Заголовок раздела. Пустой — блоки идут сразу, без заголовка. */
  title?: string;
  /** Якорь: на него ссылается форма заявки («согласен на обработку»). */
  id?: string;
  /** Крупный разделитель: «РАЗДЕЛ II. СОГЛАСИЕ…». */
  part?: boolean;
  blocks: LegalBlock[];
};

export type LegalDocument = {
  title: string;
  /** Короткая строка над заголовком. */
  label: string;
  /** Дата утверждения — выводится в шапке документа. */
  approved: string;
  sections: LegalSection[];
};
