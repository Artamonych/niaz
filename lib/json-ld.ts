/**
 * Разметка JSON-LD внутри <script>.
 *
 * `JSON.stringify` не экранирует «<», поэтому заголовок новости со строкой
 * `</script>` закрывал бы блок, и всё, что за ним, браузер читал бы как обычную
 * разметку — вплоть до выполнения чужого кода на публичной странице
 * (п. 34 бэклога). Заменяем «<» на escape-последовательность JSON: разбор
 * данных от этого не меняется, а закрыть тег строкой больше нельзя.
 *
 * `String.raw` — чтобы в исходнике стояла ровно та последовательность, которая
 * нужна в выводе, без второго уровня экранирования.
 */
export const jsonLdScript = (data: unknown) =>
  JSON.stringify(data).replaceAll('<', String.raw`\u003c`);
